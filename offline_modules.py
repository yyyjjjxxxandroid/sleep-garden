"""Package local ES modules using browser-native import maps when esbuild is absent.

No downloads are required. The module graph remains local inside the saved HTML.
This fallback supports this project's static import/export-from declarations.
"""
from pathlib import Path
import base64
import json
import re

IMPORT = re.compile(r"^((?:import|export)\s+(?:(?:\{[^}]*\}|\*\s*(?:as\s+\w+)?|\w+)\s+from\s*)?['\"])([^'\"\n]+)(['\"])", re.MULTILINE)


def bundle_modules(root: Path, entry='story-world.js'):
    sources = {}

    def collect(path):
        path = path.resolve()
        key = 'garden/' + path.relative_to(root).as_posix()
        if key in sources:
            return key
        sources[key] = ''

        def rewrite(match):
            specifier = match[2]
            if specifier == 'three':
                dependency = root / 'vendor/three/build/three.module.js'
            elif specifier.startswith('.'):
                dependency = path.parent / specifier
            else:
                raise ValueError(f'Unsupported external import: {specifier} in {path}')
            return match[1] + collect(dependency) + match[3]

        sources[key] = IMPORT.sub(rewrite, path.read_text())
        return key

    entry_key = collect(root / entry)
    imports = {key: 'data:text/javascript;base64,' + base64.b64encode(value.encode()).decode()
               for key, value in sources.items()}
    mapping = json.dumps(json.dumps({'imports': imports}))
    return ("// Browser-native offline module bundle; generated by build3d.py.\n"
            "(()=>{const map=document.createElement('script');map.type='importmap';"
            f"map.textContent={mapping};document.head.append(map);"
            f"window.GARDEN_READY=import({json.dumps(entry_key)});" + "})();\n")
